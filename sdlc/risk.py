"""Risk classification of a change (station 4).

Risk comes from deterministic signals: paths, diff size, tests, the module's history, the attempt
number. The model has no say here, so a prompt injection in the diff changes nothing. The level and
the scenario coverage decide the autonomy (policy.json):

  low / medium    lights-out, if the work order has holdout scenarios of its own; otherwise a human
  high / critical a human

Two signals are specific to the factory:
  - the attempt number: every rework moves the agent from the requirement towards the gate,
  - no scenarios: without an oracle there is nothing to measure, so there is no autonomy.

Usage:
  python3 sdlc/risk.py --base main --head HEAD [--agent] [--attempt 2] [--work-order "title"]
"""

from __future__ import annotations

import argparse
from pathlib import Path

from context import build_index
from lib import STATE, covered_by_scenarios, git, outputs, module_for_path, policy, summary_md, write_json

ORDER = ["low", "medium", "high", "critical"]
PRODUCTION = ("system/game/", "system/tools/")
TESTS = ("system/tests/", "system/bugs/tests/")


def level_for(score: int, levels: dict) -> str:
    return max((name for name in ORDER if score >= levels[name]), key=ORDER.index)


def classify(base: str, head: str, agent_authored: bool, attempt: int = 1, work_order: str = "") -> dict:
    rules = policy()
    index = build_index()
    catalog = index["modules"]
    # .factory/ is the ledger the line adds to the PR after the gates (finale). It is not a code change.
    numstat = [line.split("\t") for line in git("diff", "--numstat", f"{base}...{head}", "--", ".", ":!.factory").splitlines() if line]
    files = [{"path": p, "added": int(a) if a.isdigit() else 0, "deleted": int(d) if d.isdigit() else 0} for a, d, p in numstat]
    paths = [f["path"] for f in files]
    lines = sum(f["added"] + f["deleted"] for f in files)
    touched = sorted({m["name"] for p in paths if (m := module_for_path(p, catalog))})
    by_name = {m["name"]: m for m in catalog}

    signals = []

    def signal(name: str, points: int, detail: str) -> None:
        signals.append({"name": name, "points": points, "detail": detail})

    gate_hits = [p for p in paths if any(p.startswith(g) for g in rules["gate_paths"])]
    if gate_hits:
        signal("gates changed", 7, f"the change touches the controls: {', '.join(gate_hits[:3])}")

    critical_hits = [p for p in paths if any(p.startswith(c) for c in rules["critical_paths"])]
    critical_hits += [p for p in paths if (m := module_for_path(p, catalog)) and m.get("critical") and p not in critical_hits]
    if critical_hits:
        signal("critical path", 4, f"{len(critical_hits)} file(s) on the critical path (ADR-011)")

    sensitive_hits = [p for p in paths if any(p.startswith(s) for s in rules["sensitive_paths"])]
    if sensitive_hits:
        signal("sensitive file", 2, f"what every visitor plays or reads: {', '.join(sensitive_hits[:3])}")

    radius_critical = sorted({d for name in touched for d in by_name[name]["dependents"] if by_name[d].get("critical")} - set(touched))
    if radius_critical:
        signal("blast radius", 1, f"the change can reach the critical path: {', '.join(radius_critical)}")

    thresholds = rules["risk"]
    if lines > thresholds["large_diff_lines"]:
        signal("large diff", 2, f"{lines} changed lines")
    elif lines > thresholds["medium_diff_lines"]:
        signal("medium diff", 1, f"{lines} changed lines")

    main_code = [p for p in paths if p.startswith(PRODUCTION) and not p.endswith(".test.ts")]
    test_code = [p for p in paths if p.startswith(TESTS)]
    if main_code and not test_code:
        signal("no tests", 2, "production code changed without any change to the tests")

    incidents = sorted({i["title"] for name in touched for i in by_name[name]["incidents"]})
    if incidents:
        signal("incident history", 1, "; ".join(incidents))

    unstable = [name for name in touched if by_name[name]["churn_30d"] >= thresholds["unstable_churn_30d"]]
    if unstable:
        signal("unstable module", 1, f"many changes in 30 days: {', '.join(unstable)}")

    if agent_authored:
        signal("author: agent", 1, "a change generated by an agent")

    if attempt > 1:
        signal("rework", attempt - 1, f"attempt {attempt}: the agent iterates towards the gates, not the requirement")

    covered = covered_by_scenarios(work_order) if work_order else False
    if work_order and not covered:
        signal("no scenarios", 2, "the work order has no holdout scenarios of its own")

    score = sum(s["points"] for s in signals)
    level = level_for(score, thresholds["levels"])
    mode = rules["autonomy"][level]
    if mode == "lights-out" and not covered:
        autonomy, why = "human", "no holdout scenarios: nothing to measure the change with but a human"
    elif mode == "lights-out":
        autonomy, why = "lights-out", f"risk {level} and the work order is covered by scenarios"
    else:
        autonomy, why = "human", f"policy: risk {level} needs a human"
    reviewers = []
    for name in touched:
        for owner in [o for o in by_name[name]["owners_real"] if not o.get("agent")][:1]:
            reviewers.append({"module": name, "name": owner["name"]})
    return {
        "level": level,
        "score": score,
        "signals": signals,
        "modules": touched,
        "files": files,
        "lines": lines,
        "needs_human": autonomy == "human",
        "autonomy": autonomy,
        "autonomy_reason": why,
        "attempt": attempt,
        "covered": covered,
        "suggested_reviewers": reviewers,
    }


def markdown(result: dict) -> str:
    icon = {"low": "🟢", "medium": "🟡", "high": "🟠", "critical": "🔴"}[result["level"]]
    out = [f"### {icon} Risk: **{result['level']}** ({result['score']} pts)", ""]
    if result["signals"]:
        out += ["| signal | pts | details |", "|---|---|---|"]
        out += [f"| {s['name']} | +{s['points']} | {s['detail']} |" for s in result["signals"]]
    else:
        out.append("No risk signals.")
    if result["needs_human"]:
        out += ["", f"👤 Autonomy: **human** ({result['autonomy_reason']}). A person decides; the line waits for them once its human step has a wait (lesson 9)."]
    else:
        out += ["", f"🌑 Autonomy: **lights-out** ({result['autonomy_reason']})."]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--base", required=True)
    parser.add_argument("--head", default="HEAD")
    parser.add_argument("--agent", action="store_true", help="a change generated by an agent")
    parser.add_argument("--attempt", type=int, default=1)
    parser.add_argument("--work-order", default="")
    parser.add_argument("--out", default=str(STATE / "risk.json"))
    args = parser.parse_args()

    result = classify(args.base, args.head, args.agent, args.attempt, args.work_order)
    write_json(Path(args.out), result)
    text = markdown(result)
    print(text)
    summary_md(text)
    outputs(level=result["level"], score=result["score"], needs_human=str(result["needs_human"]).lower(),
            autonomy=result["autonomy"])


if __name__ == "__main__":
    main()
